function offsetDateStr(daysOffset: number, baseDate: Date = new Date()): string {
  const shifted = new Date(baseDate.getTime() + daysOffset * 86_400_000);
  return getLibraryDateString(shifted, 'Asia/Manila');
}

function isoOnDay(dateStr: string, hhmm: string): string {
  return new Date(`${dateStr}T${hhmm}:00+08:00`).toISOString();
}

