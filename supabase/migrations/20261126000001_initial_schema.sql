-- Link new Supabase Auth users to an existing profile by email automatically.
create or replace function public.link_auth_user_to_profile()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  update public.profiles
  set auth_user_id = new.id
  where lower(email) = lower(new.email)
    and auth_user_id is null;
  return new;
end;
$$;

drop trigger if exists trg_link_auth_user_to_profile on auth.users;
create trigger trg_link_auth_user_to_profile
  after insert on auth.users
  for each row execute function public.link_auth_user_to_profile();

-- ---------------------------------------------------------------------------
-- 4. Atomic Attendance RPCs (Option A: explicit Time-In / Time-Out modes)
-- ---------------------------------------------------------------------------
create or replace function public.clock_in_student(
  p_student_name text,
  p_scanned_by text default null
)
returns text
language plpgsql
security invoker
as $$
declare
  v_profile_id uuid;
begin
  if exists (
    select 1 from public.attendance_logs
    where student_name = p_student_name and is_active = true
  ) then
    return 'already_in';
  end if;

  select id into v_profile_id
  from public.profiles
  where full_name = p_student_name
  limit 1;

  insert into public.attendance_logs (
    student_name,
    student_profile_id,
    is_active,
    scanned_by,
    verification_method
  ) values (
    p_student_name,
    v_profile_id,
    true,
    p_scanned_by,
    'qr'
  );

  return 'ok';
exception
  when unique_violation then
    return 'already_in';
end;
$$;

create or replace function public.clock_out_student(p_student_name text)
returns text
language plpgsql
security invoker
as $$
declare
  v_updated integer;
begin
  update public.attendance_logs
  set is_active = false,
      clocked_out_at = now()
  where student_name = p_student_name
    and is_active = true;

  get diagnostics v_updated = row_count;
  if v_updated = 0 then
    return 'not_in';
  end if;

  return 'ok';
end;
$$;

