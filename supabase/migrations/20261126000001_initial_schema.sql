-- 2. Core Tables
-- ---------------------------------------------------------------------------
create table if not exists public.library_sections (
  id text primary key,
  code text not null unique,
  name text not null unique,
  location text not null,
  created_at timestamptz not null default now()
);

create table if not exists public.profiles (
  id uuid primary key default gen_random_uuid(),
  auth_user_id uuid unique references auth.users(id) on delete set null,
  university_id text not null unique,
  email text not null unique,
  full_name text not null,
  role text not null check (role in ('STUDENT', 'OIC', 'ADMIN')),
  department text not null default '',
  done_hours numeric(6, 2) not null default 0,
  required_hours integer not null default 60,
  active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.section_memberships (
  profile_id uuid not null references public.profiles(id) on delete cascade,
  section_id text not null references public.library_sections(id) on delete cascade,
  primary key (profile_id, section_id)
);

create table if not exists public.shifts (
  id bigint generated by default as identity primary key,
  day_label text not null,
  shift_date text not null,
  start_time text not null,
  end_time text not null,
  section text not null,
  section_id text references public.library_sections(id) on delete set null,
  oic_name text not null,
  student_name text not null,
  student_profile_id uuid references public.profiles(id) on delete set null,
  status text not null default 'Scheduled' check (status in ('Scheduled', 'Completed', 'Missed')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.attendance_logs (
  id bigint generated by default as identity primary key,
  student_name text not null,
  student_profile_id uuid references public.profiles(id) on delete set null,
  shift_id bigint references public.shifts(id) on delete set null,
  clocked_in_at timestamptz not null default now(),
  clocked_out_at timestamptz,
  is_active boolean not null default true,
  scanned_by text,
  verification_method text not null default 'qr',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

-- Enforce Option A attendance guard: a student can only have one active clock-in at a time.
create unique index if not exists attendance_logs_one_active_per_student
  on public.attendance_logs (student_name)
  where (is_active = true);

create table if not exists public.tasks (
  id bigint generated by default as identity primary key,
  title text not null,
  type text not null check (type in ('Shelving', 'Circulation', 'Inventory')),
  section text not null,
  assigned_to text not null,
  assigned_to_profile_id uuid references public.profiles(id) on delete set null,
  shift_id bigint references public.shifts(id) on delete set null,
  status text not null default 'Assigned' check (status in ('Assigned', 'In Progress', 'Done', 'Verified')),
  created_by text,
  completed_at timestamptz,
  verified_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.duty_requests (
  id bigint generated by default as identity primary key,
  kind text not null check (kind in ('Swap', 'Leave')),
  shift_id bigint references public.shifts(id) on delete set null,
  shift_label text not null,
  reason text not null,
  requester text not null,
  requester_profile_id uuid references public.profiles(id) on delete set null,
  submitted_on text not null,
  attachment_name text,
  status text not null default 'Pending OIC' check (status in ('Pending OIC', 'Endorsed', 'Approved', 'Rejected')),
  endorsed_by text,
  endorsed_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.visitor_entries (
  id bigint generated by default as identity primary key,
  name text not null,
  kind text not null check (kind in ('Visitor', 'Baggage', 'Paper')),
  detail text not null,
  entry_time text not null,
  returned boolean,
  section text,
  recorded_by text,
  deleted_at timestamptz,
  delete_reason text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

